function make(
  code: LocaleCode,
  name: string,
  nativeName: string,
  speech: string,
  values: string[],
  dir?: "rtl",
): LocalePack {
  if (values.length !== K.length)
    throw new Error(
      `${code}: expected ${K.length} translations, got ${values.length}`,
    );
  return {
    code,
    name,
    nativeName,
    speech,
    dir,
    c: Object.fromEntries(
      K.map((key, index) => [key, values[index]]),
    ) as Record<CopyKey, string>,
  };
}

