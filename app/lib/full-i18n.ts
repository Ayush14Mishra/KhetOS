function preserveSpacing(original: string, translated: string) {
  const leading = original.match(/^\s*/)?.[0] ?? "";
  const trailing = original.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

export function translateInterfaceText(
  locale: LocaleCode,
  original: string,
): string {
  if (locale === "en" || !original.trim()) return original;
  const packForLocale = packs[locale] ?? packs.hi;
  const trimmed = original.trim();
  let result = trimmed;

  const screenExact = translateScreenPhrase(locale, trimmed);
  if (screenExact) return preserveSpacing(original, screenExact);

  const exactKey = phraseKeys.find((key) => englishPhrases[key] === trimmed);
  if (exactKey)
    return preserveSpacing(original, packForLocale.phrases[exactKey]);

  for (const key of [...phraseKeys].sort(
    (a, b) => englishPhrases[b].length - englishPhrases[a].length,
  )) {
    result = result.replaceAll(englishPhrases[key], packForLocale.phrases[key]);
  }

  const englishCopy = localeByCode.en.c;
  const targetCopy = localeByCode[locale].c;
  for (const english of [...copyPairs].sort((a, b) => b.length - a.length)) {
    const key = (
      Object.keys(englishCopy) as Array<keyof typeof englishCopy>
    ).find((candidate) => englishCopy[candidate] === english);
    if (key)
      result = result.replace(
        new RegExp(
          `\\b${english.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`,
          "gi",
        ),
        targetCopy[key],
      );
  }

  if (!/(?:https?:\/\/|[A-Za-z0-9]\.[a-z]{2,})/i.test(result)) {
    for (const key of termKeys) {
      result = result.replace(
        new RegExp(`\\b${englishTerms[key]}\\b`, "gi"),
        packForLocale.terms[key],
      );
    }
  }
  return preserveSpacing(original, result);
}

export function translatePhrase(locale: LocaleCode, key: PhraseKey): string {
  return (packs[locale] ?? packs.hi).phrases[key];
}

export function translateTerm(locale: LocaleCode, key: TermKey): string {
  return (packs[locale] ?? packs.hi).terms[key];
}

