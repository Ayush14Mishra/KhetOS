function pack(phrases: string[], terms: string[]): FullPack {
  if (
    phrases.length !== phraseKeys.length ||
    terms.length !== termKeys.length
  ) {
    throw new Error(
      `Full translation pack mismatch: ${phrases.length}/${terms.length}`,
    );
  }
  return {
    phrases: Object.fromEntries(
      phraseKeys.map((key, index) => [key, phrases[index]]),
    ) as Record<PhraseKey, string>,
    terms: Object.fromEntries(
      termKeys.map((key, index) => [key, terms[index]]),
    ) as Record<TermKey, string>,
  };
}

